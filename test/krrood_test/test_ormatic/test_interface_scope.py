"""
An interface generated by ORMatic takes only what it maps and what it builds on.
"""

from krrood.ormatic.ormatic import ORMatic

from ..dataset import (
    alternative_mappings_construction_order,
    interface_typed_fields,
    ormatic_interface,
)

# %% alternative mappings


def test_interface_takes_no_alternative_mapping_from_a_module_it_does_not_map() -> None:
    """
    A mapping that is merely imported in the process, from a module the interface
    neither maps nor builds on, stays out of the interface.
    """
    ormatic = ORMatic.from_package(
        packages=[interface_typed_fields],
        ormatic_interface_dependencies=[],
        ignored_classes=set(),
        type_mappings={},
        ignore_krrood_test_classes=False,
    )

    leaked_mappings = {
        mapping
        for mapping in ormatic.alternative_mappings
        if mapping.__module__ == alternative_mappings_construction_order.__name__
    }
    assert leaked_mappings == set()


# %% reused tables


def test_interface_building_on_nothing_reuses_no_table_of_a_loaded_interface() -> None:
    """
    The tables of an interface that is loaded in the process, but that the new interface
    does not build on, are not reused by it.
    """
    assert ormatic_interface.Base.registry.mappers

    ormatic = ORMatic.from_package(
        packages=[interface_typed_fields],
        ormatic_interface_dependencies=[],
        ignored_classes=set(),
        type_mappings={},
        ignore_krrood_test_classes=False,
    )

    assert ormatic.externally_mapped_classes == {}
