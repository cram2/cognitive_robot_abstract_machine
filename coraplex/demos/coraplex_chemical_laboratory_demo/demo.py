"""
A Toyota HSR runs a sample-analysis round through a chemical laboratory.

The laboratory holds a long preparation bench along the west wall, a central
analysis island crowded with glassware, and two scientist desks by the east wall.
The robot does what a laboratory assistant robot does between experiments: it
carries the incoming sample flask from the preparation bench to the analysis
island, brings the requested reagent bottle from the island to the scientist's
desk, and returns the empty test-tube rack from the island to the preparation
bench on its way back.
"""

